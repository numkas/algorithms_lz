#Импортируем функцию randint из библиотеки random и даем ей название sor
from random import randint as sor
#создаем пустой список для хранения чисел которые сделал наш рандомайзер
a = []
#цикл будет выполнятся 100 раз и мы получим 100 разных чисел
for i in range ( 0, 100 ):
    #задаем лимиты в которых нам нужно сгенирировать наши числа
    a.append(sor( 0,  100_000 ))
#выводим наш список
print(a)
#флажек который будет выполнять цикл пока список не будет отсортирован т.е примит значение Folse где не будет происходить сравнения
stop_flag = True
#задаем пееменную для посчета количества сравнений
kolvo_sravneniy1 = 0
#цикл будет продолжаться пока stop_flag равен True
while stop_flag is True:
    #сбрасываем массива до значения folse означающее что список уже отсортирован
    stop_flag = False
    #цикл проходит по всем значениям списка от первого до предпоследнего
    for i in range( 0, len(a) - 1):
        #прибовляем к счетчику  1 за одно сравнение
        kolvo_sravneniy1 +=1
        #если текущий эдемент меньше следующего то меняем их местами
        if a[i] < a[i + 1]:
            #сохраняем значение текущего элемента в переменной swap  или любой другой
            swap = a[i]
            #записываем на место текущего след элемнт
            a[i] = a[i + 1]
            #и в следующий элемент записываем сохраненное ранее значение a[i]
            a[i + 1] = swap
            #и выводим каждый итог сравнения
            print(a)
            #одно сравнение произошло значит true и повторяем сравнение
            stop_flag = True
#и под еонеу выводим конечный отсортированный список
print(a)
#копируем нащ список и записываем его в другую перемнную для сортировки выборкой
b = a.copy() 
#создаем новый пустой список в который поочередно будем сортировать элементы выборкой
c = []
#задаем переменню для подсчета сравнений
kolvo_sravneniy2 = 0
#программа будет работать пока в b не останется ни одног элемента
while len(b) > 0:
    #выводим наш список
    print(b)
    #предпологаем что элемент b  является максимальным в списке
    max = b[0]
    #уикл будет сравнивать с каждым элеметом b 
    for i in range(0, len(b)):
        #за каждое сравнение прибовляеи к нашему счетчику 1
        kolvo_sravneniy2 += 1
        #если найдется переменная которая больше нашего предположения то
        if b[i] < max:
        #перезаписываем наш максимальный элемент
         max = b[i]
    #добавляем наш максимальный элемет в список с
    c.append(max)
    #убираем наш максимальный элемент из списка b
    b.remove(max)
#выводим наш отсортированный список
print(c)
#воводим количество сравнений для пузырька
print(f"Количество сравнений для пузырька {kolvo_sravneniy1}")
#и для выборки
print(f"Количество сравнений для выборки {kolvo_sravneniy2}")

