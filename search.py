#Импортируем функцию randint из библиотеки random и даем ей название sor
from random import randint as sor
#создаем пустой список для хранения чисел которые сделал наш рандомайзер
a = []
#команда sort сортирует наш список 
a.sort()
#цикл будет выполнятся 100 раз и мы получим 100 разных чисел
for i in range ( 0, 100 ):
    #задаем лимиты в которых нам нужно сгенирировать наши числа
    a.append(sor( 0,  100_000 ))
#выводим наш список
print(a)
#звдвем переменную которую нужно найти в списке
e = 53535
#запускаем цикл в котором i принимает значенияот начала до конца массива а
for i in range(len(a)):
    #в случае если находится элемент который мы ищем
    if a[i] == e:
        #выводим его индекс
        print(i)
        #ломаем цикл
        break
#и в случае если не находится такой элемент
else:
    #выводим
    print("Элемент не найден")
#задаем начальный индекс левой границы поиска ну или самый левый элемент 
first = 0
#задаем начальный индекс правой границы поиска или самый правый элемент
last = len(a)-1
#присваиваем элементу i  -1
i = -1
#нащ цикл будет выполнятся пока левая граница не найдет до правой и элемент не найден
while (first <= last) and (i == -1):
    #находим индекс элемента находящегося на середине а
    mid = (first+last)//2
    #если среднй элемент равен нашему искомому числу
    if a[mid] == e:
        #то в i  записываем индекс среднего элемента
        i = mid
    else:
        #если искомое число меньше середины списка то
        if e<a[mid]:
            #сдвигаем его в лево и работаем с левой частью
            last = mid -1
        #если не равен и не меньше середины то остается только больше середины и следовательно
        else:
            #сдвигаем его в право и работаем с правой частью
            first = mid +1
#если знаечние i  так и осталось -1
if i == -1:
    #то выводим что элемент мы не нашли
    print("Элемент не найден")
#а в противоположном случае
else:
    #выводи индекс i 
    print(i)
        

